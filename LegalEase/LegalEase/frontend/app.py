def init_state() -> None:
    """Create the session-state keys used by the app."""
    defaults = {
        "doc_choice": DOCUMENT_TYPES[0],
        "custom_type": "",
        "parties": "",
        "terms": "",
        "dates": "",
        "doc_ready": False,      # True after a successful generation
        "original_text": "",     # AI draft exactly as returned by the backend
        "editor_text": "",       # user-editable version (bound to the text area)
        "doc_type_used": "",
        "terms_used": "",
    }
    for key, value in defaults.items():
        st.session_state.setdefault(key, value)


def load_sample() -> None:
    """Callback: fill the form with example data."""
    st.session_state.doc_choice = SAMPLE["doc_choice"]
    st.session_state.parties = SAMPLE["parties"]
    st.session_state.terms = SAMPLE["terms"]
    st.session_state.dates = SAMPLE["dates"]


def reset_editor() -> None:
    """Callback: discard edits and restore the original AI draft."""
    st.session_state.editor_text = st.session_state.original_text


def clear_document() -> None:
    """Callback: remove the generated document from the session."""
    st.session_state.doc_ready = False
    st.session_state.original_text = ""
    st.session_state.editor_text = ""


