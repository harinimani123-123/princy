# UI pieces
# ---------------------------------------------------------------------------
def validate_inputs(doc_type: str, parties: str, terms: str, dates: str) -> list[str]:
    """Return a list of human-readable validation errors (empty = valid)."""
    errors = []
    checks = [
        ("Document type", doc_type, MAX_DOCUMENT_TYPE_LENGTH),
        ("Parties", parties, MAX_PARTIES_LENGTH),
        ("Terms and conditions", terms, MAX_TERMS_LENGTH),
        ("Effective date", dates, MAX_DATES_LENGTH),
    ]
    for label, value, limit in checks:
        if not value.strip():
            errors.append(f"{label} is required.")
        elif len(value.strip()) > limit:
            errors.append(f"{label} is too long ({len(value.strip())}/{limit} characters).")
    return errors


def render_sidebar() -> None:
    with st.sidebar:
        st.header("About LegalEase")
        st.write(
            "Describe the agreement you need and Gemini drafts it for you. "
            "Edit the draft, then download it as TXT, DOCX or PDF."
        )
        st.markdown(
            "1. Choose a document type\n2. Enter parties, terms and date\n"
            "3. Generate and edit the draft\n4. Download and get it reviewed"
        )
        st.divider()
        st.caption(f"Backend: `{BACKEND_URL}`")
        if st.button("Check backend connection"):
            ok, message = check_backend()
            (st.success if ok else st.error)(message)
        st.divider()
        st.caption(
            "Your inputs are sent to your local backend and then to Google Gemini for drafting. "
            "LegalEase does not store generated documents."
        )


def render_form() -> None:
    """Left column: input form and generation logic."""
    st.markdown('<div class="le-step">Step 1</div>', unsafe_allow_html=True)
    st.subheader("Document details")

    st.selectbox("Document type", DOCUMENT_TYPES, key="doc_choice")
    if st.session_state.doc_choice == "Custom Agreement":
        st.text_input(
            "Custom document type",
            key="custom_type",
            max_chars=MAX_DOCUMENT_TYPE_LENGTH,
            placeholder="e.g. Partnership Agreement, Loan Agreement",
        )

    st.text_area(
        "Parties involved",
        key="parties",
        height=110,
        max_chars=MAX_PARTIES_LENGTH,
        placeholder="e.g. Jane Doe (Service Provider), TechNova Inc. (Client)",
        help="Names and roles of everyone involved. Anything you leave out becomes [MISSING INFORMATION].",
    )
    st.text_area(
        "Terms and conditions",
        key="terms",
        height=170,
        max_chars=MAX_TERMS_LENGTH,
        placeholder="Separate each term with a semicolon, e.g.\n"
                    "Payment within 30 days of invoice; Work delivered by May 15, 2025; "
                    "Either party may terminate with 15 days notice",
        help="Use semicolons (;) or new lines between terms.",
    )
    st.text_input(
        "Effective date",
        key="dates",
        max_chars=MAX_DATES_LENGTH,
        placeholder="e.g. April 15, 2025",
    )

    generate_col, sample_col = st.columns([1, 1])
    with generate_col:
        generate_clicked = st.button("Generate Document", type="primary")
    with sample_col:
        st.button("Load example", on_click=load_sample)

    if not generate_clicked:
        return

    doc_type = (
        st.session_state.custom_type
        if st.session_state.doc_choice == "Custom Agreement"
        else st.session_state.doc_choice
    ).strip()
    parties = st.session_state.parties.strip()
    terms = st.session_state.terms.strip()
    dates = st.session_state.dates.strip()

    problems = validate_inputs(doc_type, parties, terms, dates)
    if st.session_state.doc_choice == "Custom Agreement" and not doc_type:
        problems = ["Please enter the custom document type."] + [
            p for p in problems if not p.startswith("Document type")
        ]
    if problems:
        for problem in problems:
            st.error(problem)
        return

    payload = {"document_type": doc_type, "parties": parties, "terms": terms, "dates": dates}
    with st.spinner("Gemini is drafting your document... this can take up to a minute."):
        data, error = request_document(payload)

    if error:
        st.error(error)
        return

    # Must happen before the editor widget is created in this run.
    st.session_state.original_text = data["content"]
    st.session_state.editor_text = data["content"]
    st.session_state.doc_type_used = data.get("document_type") or doc_type
    st.session_state.terms_used = terms
    st.session_state.doc_ready = True
    st.success("Document generated successfully. Review and edit it on the right.")


def render_preview() -> None:
    """Right column: editable preview and downloads."""
    st.markdown('<div class="le-step">Step 2</div>', unsafe_allow_html=True)
    st.subheader("Document preview")

    if not st.session_state.doc_ready:
        st.info("Your generated document will appear here. Fill in the form and click "
                "**Generate Document**.")
        return

    st.text_area(
        "Edit the document below (changes are kept automatically and used for downloads)",
        key="editor_text",
        height=560,
    )

    text = st.session_state.editor_text
    missing = count_missing_information(text)
    if missing:
        st.warning(
            f"{missing} `[MISSING INFORMATION]` placeholder(s) remain. Replace them with the "
            "correct details before using this document."
        )
    if not text.strip():
        st.error("The document is empty, so downloads are disabled. Use 'Reset to AI draft'.")

    action_col, clear_col = st.columns(2)
    with action_col:
        st.button("Reset to AI draft", on_click=reset_editor)
    with clear_col:
        st.button("Clear document", on_click=clear_document)

    if not text.strip():
        return

    doc_type = st.session_state.doc_type_used
    terms = st.session_state.terms_used
    include_table = False
    if len(split_terms(terms)) >= 2:
        include_table = st.checkbox("Include a key-terms table in DOCX and PDF", value=True)
    table_terms = terms if include_table else ""

    st.markdown("##### Download")
    base = f"legalease_{slugify(doc_type)}"
    txt_col, docx_col, pdf_col = st.columns(3)

    with txt_col:
        st.download_button(
            "Download TXT", data=format_txt(text), file_name=f"{base}.txt",
            mime="text/plain", key="dl_txt",
        )
    with docx_col:
        try:
            docx_bytes = build_docx(text, doc_type, table_terms)
            st.download_button(
                "Download DOCX", data=docx_bytes, file_name=f"{base}.docx",
                mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                key="dl_docx",
            )
        except Exception as exc:  # noqa: BLE001
            st.error(f"DOCX export failed: {type(exc).__name__}: {exc}")
    with pdf_col:
        try:
            pdf_bytes = build_pdf(text, doc_type, table_terms)
            st.download_button(
                "Download PDF", data=pdf_bytes, file_name=f"{base}.pdf",
                mime="application/pdf", key="dl_pdf",
            )
        except Exception as exc:  # noqa: BLE001
            st.error(f"PDF export failed: {type(exc).__name__}: {exc}")


def main() -> None:
    st.set_page_config(page_title="LegalEase", page_icon="\u2696\ufe0f", layout="wide")
    init_state()
    st.markdown(CSS, unsafe_allow_html=True)

    st.markdown(
        '<div class="le-banner"><h1>\u2696\ufe0f LegalEase</h1>'
        "<p>AI-powered legal document generator - draft, edit and download in minutes.</p></div>",
        unsafe_allow_html=True,
    )
    st.warning(DISCLAIMER)
    render_sidebar()

    form_col, preview_col = st.columns([1, 1.35], gap="large")
    with form_col:  # runs first so a new draft is stored before the editor is drawn
        render_form()
    with preview_col:
        render_preview()

    st.caption(
        "LegalEase creates AI-assisted drafts. They are not legal advice and are not guaranteed to "
        "be valid or enforceable in any jurisdiction."
    )


main()
