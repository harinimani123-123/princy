# Backend communication
# ---------------------------------------------------------------------------
def describe_http_error(response: requests.Response) -> str:
    """Turn an error response from the backend into a readable message."""
    try:
        detail = response.json().get("detail")
    except (ValueError, AttributeError):
        detail = None

    if isinstance(detail, str) and detail.strip():
        return detail
    if isinstance(detail, list):  # FastAPI/Pydantic validation errors
        messages = []
        for item in detail:
            if isinstance(item, dict):
                field = item.get("loc", ["input"])[-1]
                messages.append(f"{field}: {item.get('msg', 'invalid value')}")
        if messages:
            return "Please fix the following: " + "; ".join(messages)
    return f"The backend returned an error (HTTP {response.status_code})."


def request_document(payload: dict) -> tuple[dict | None, str | None]:
    """Call ``POST /generate``. Returns ``(data, error_message)``."""
    url = f"{BACKEND_URL}/generate"
    try:
        response = requests.post(url, json=payload, timeout=(CONNECT_TIMEOUT_S, READ_TIMEOUT_S))
    except requests.exceptions.ConnectionError:
        return None, (
            f"Cannot connect to the backend at {BACKEND_URL}. Start it in another terminal with: "
            "`uvicorn backend.main:app --reload --host 127.0.0.1 --port 8000`"
        )
    except requests.exceptions.Timeout:
        return None, (
            "The backend took too long to respond. Gemini may be busy - please try again."
        )
    except requests.exceptions.RequestException as exc:
        return None, f"Request failed: {type(exc).__name__}."

    if response.status_code != 200:
        return None, describe_http_error(response)

    try:
        data = response.json()
    except ValueError:
        return None, "The backend returned a malformed (non-JSON) response."

    content = data.get("content") if isinstance(data, dict) else None
    if not isinstance(data, dict) or data.get("success") is not True or not isinstance(content, str) \
            or not content.strip():
        return None, "The backend response was incomplete or the AI failed to produce a document."
    return data, None


def check_backend() -> tuple[bool, str]:
    """Ping ``GET /health``."""
    try:
        response = requests.get(f"{BACKEND_URL}/health", timeout=(CONNECT_TIMEOUT_S, 10))
        if response.status_code == 200 and response.json().get("status") == "healthy":
            return True, "Backend is running and healthy."
        return False, f"Backend answered with HTTP {response.status_code}."
    except requests.exceptions.RequestException:
        return False, f"Backend is not reachable at {BACKEND_URL}."
    except ValueError:
        return False, "Backend returned an unexpected response."


# ---------------------------------------------------------------------------
# Export helpers (cached so re-runs while editing stay fast)
# ---------------------------------------------------------------------------
@st.cache_data(show_spinner=False)
def build_docx(text: str, doc_type: str, terms: str) -> bytes:
    return format_docx(text, doc_type, terms or None)


@st.cache_data(show_spinner=False)
def build_pdf(text: str, doc_type: str, terms: str) -> bytes:
    return format_pdf(text, doc_type, terms or None)


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")
    return slug[:50] or "document"


